export function removeEvent<S extends ActivityState & { teacherVacations?: VacationPeriods }>(
  state: S,
  id: string,
  institutional: InstitutionalEventSnapshot[],
): S {
  if (!state.events.some((event) => event.id === id))
    throw new DomainError('O evento não existe mais.');
  const next = {
    ...state,
    events: state.events.filter((event) =>
      vacationIds.has(id) ? !vacationIds.has(event.id) : event.id !== id,
    ),
  };
  if (vacationIds.has(id)) delete next.teacherVacations;
  return recalculateCalendar(next, institutional);
}

/** Occurrence identity is independent of source documents and descriptive metadata. */
function sameOccurrence(a: CalendarEvent, b: CalendarEvent) {
  return (
    a.name.toLocaleLowerCase() === b.name.trim().toLocaleLowerCase() &&
    a.start === b.start &&
    a.end === b.end &&
    equalValues(a.notice?.admission, b.notice?.admission) &&
    equalValues([...a.scope.offers].sort(), [...b.scope.offers].sort())
  );
}

/** A date as filled in a form: the link never comes from the form fields. */
export type DateInput<S extends ActivityState> = Omit<S['events'][number], 'activity'> & {
  activity?: never;
};

type Linked<S extends ActivityState> = S['events'][number];

/** The date without any link it may carry at runtime; the command decides the link. */
function withoutLink<S extends ActivityState>(date: DateInput<S>) {
  const { activity: _activity, ...rest } = date as Linked<S>;
  return rest;
}

const givenLink = (date: object) => (date as { activity?: ActivityRef }).activity;

/**
 * Plans a new date for an activity. The link comes from the context where the date is filled (the
 * activity being filled), never from the form, and needs an activity generated by the current
 * configuration that covers the offers of the date.
 */
export function planActivityDate<S extends ActivityState>(
  state: S,
  activity: ActivityRef,
  date: DateInput<S>,
  institutional: InstitutionalEventSnapshot[],
): S {
  if (givenLink(date) !== undefined && !sameActivity(givenLink(date), activity))
    throw new DomainError('A atividade da data vem do contexto do preenchimento.');
  if (!generatedActivity(generatedActivities(state), activity))
    throw new DomainError('Atividade inválida para este calendário.');
  return applyDate(state, { ...withoutLink(date), activity } as Linked<S>, institutional);
}

/** Creates a date of the campus: it has no activity, whatever the form says. */
export function createCampusDate<S extends ActivityState>(
  state: S,
  date: DateInput<S>,
  institutional: InstitutionalEventSnapshot[],
): S {
  if (givenLink(date) !== undefined)
    throw new DomainError('Uma data do campus não tem atividade vinculada.');
  return applyDate(state, withoutLink(date) as Linked<S>, institutional);
}

/**
 * Edits a saved date, keeping the link it has: a date of the campus stays without activity and a
 * linked date keeps its link, even without a generated activity. Only correcting the linked
 * activity changes it.
 */
export function updateDate<S extends ActivityState>(
  state: S,
  date: DateInput<S>,
  institutional: InstitutionalEventSnapshot[],
): S {
  const saved = state.events.find((item) => item.id === date.id);
  if (!saved) throw new DomainError('O evento não existe mais. Reabra o calendário.');
  if (givenLink(date) !== undefined && !sameActivity(givenLink(date), saved.activity))
    throw new DomainError('Uma data salva não perde nem troca a atividade vinculada.');
  const rest = withoutLink(date);
  const event = (saved.activity ? { ...rest, activity: saved.activity } : rest) as Linked<S>;
  return applyDate(state, event, institutional, saved);
}

/**
 * The saved date with its link corrected to `activity`, after the checks of `changeActivity`: the
 * date is under “Vínculo a conferir”, the new link is another activity generated by the current
 * configuration that covers every offer of the date and, for a stage, a position no other date
 * holds; the date, unchanged otherwise (an automatic distribution of stages is dropped when the new
 * activity is not an assessment interval), fits the new activity as an edited date would (interval
 * and cycle of a stage, references out of the year). The save boundary keeps the same contract
 * (`linkCorrected` in `validateLinks`).
 */
function correctedDate<S extends ActivityState>(
  state: S,
  eventId: string,
  activity: ActivityRef | undefined,
  // Computed once by callers that check several activities for the same state.
  context = { generated: generatedActivities(state), toReview: linksToReview(state) },
): S['events'][number] {
  const saved = state.events.find((item) => item.id === eventId);
  if (!saved) throw new DomainError('A data não existe mais. Reabra o calendário.');
  if (!saved.activity)
    throw new DomainError('Uma data do campus não passa a ter atividade vinculada.');
  if (!activity)
    throw new DomainError(
      'A correção troca a atividade vinculada e não remove o vínculo. Para desfazê-lo, exclua a data.',
    );
  if (sameActivity(saved.activity, activity))
    throw new DomainError('A data já está vinculada a esta atividade.');
  if (!context.toReview.has(eventId))
    throw new DomainError(
      'Só uma data em Vínculo a conferir tem a atividade vinculada corrigida. Esta data já conta para a atividade.',
    );
  const row = generatedActivity(context.generated, activity);
  if (!row) throw new DomainError('Atividade inválida para este calendário.');
  if (!coversAllOffers(state, row, saved))
    throw new DomainError(
      'A atividade escolhida não abrange todas as ofertas da data. Ajuste as ofertas da data antes de corrigir o vínculo.',
    );
  if (
    isStageActivity(activity) &&
    state.events.some((other) => other.id !== eventId && sameActivity(other.activity, activity))
  )
    throw new DomainError('Uma etapa só passa a esta posição quando nenhuma outra data a ocupa.');
  const corrected = { ...saved, activity };
  // Automatic distribution belongs to an assessment interval only (`normalizeOfferCalendar`).
  if (!isAssessmentStage(activity)) delete corrected.assessmentAutoStart;
  validateActivityRecord(state, corrected, { stageInterval: true });
  const schoolDay = schoolDayIssue(state, corrected) ?? activityExtensionIssue(corrected);
  if (schoolDay) throw new DomainError(schoolDay);
  const cycleIssue = assessmentCycleIssue(state, corrected);
  if (cycleIssue) throw new DomainError(cycleIssue);
  return corrected;
}

/**
 * Generated activities a saved date can be corrected to (`changeActivity`), in the order of the
 * activity plan, those of the same declaration first. Empty for a date of the campus or a date
 * that is not under “Vínculo a conferir”.
 */
export function activityChangeOptions(state: ActivityState, eventId: string): ActivityPlanItem[] {
  const saved = state.events.find((item) => item.id === eventId);
  if (!saved?.activity) return [];
  const context = { generated: generatedActivities(state), toReview: linksToReview(state) };
  if (!context.toReview.has(eventId)) return [];
  const options = [...context.generated.values()].filter((row) => {
    try {
      correctedDate(state, eventId, row.activity, context);
      return true;
    } catch (error) {
      if (error instanceof DomainError) return false;
      throw error;
    }
  });
  const same = (row: ActivityPlanItem) => row.activity.activityId === saved.activity!.activityId;
  return [...options.filter(same), ...options.filter((row) => !same(row))];
}

/**
 * Why the date is under “Vínculo a conferir” when its link can be corrected now: under review in
 * the current state and in the saved one, whose review the save boundary checks (`linkCorrected`
 * in `validateLinks`). A date put under review only by unsaved changes is corrected once they are
 * saved.
 */
export function correctableLinkIssue(
  saved: ActivityState,
  state: ActivityState,
  eventId: string,
): LinkIssue | undefined {
  const issue = linksToReview(state).get(eventId);
  return issue && linksToReview(saved).has(eventId) ? issue : undefined;
}

/** What correcting the linked activity of a date changes, shown before it is applied. */
export interface ActivityChangePreview {
  /** The date, whose description, dates, offers and ID stay as they are. */
  date: CalendarEvent;
  from: { activity: ActivityRef; name?: string; issue?: LinkIssue };
  to: { activity: ActivityRef; name: string };
  /** Why the date stays under “Vínculo a conferir” after the correction; undefined: it counts. */
  issueAfter?: LinkIssue;
}

/** Preview of `changeActivity`: refuses as the command does and changes nothing. */
export function previewActivityChange<S extends ActivityState>(
  state: S,
  eventId: string,
  activity: ActivityRef | undefined,
  institutional: InstitutionalEventSnapshot[],
): ActivityChangePreview {
  const saved = state.events.find((item) => item.id === eventId);
  const next = changeActivity(state, eventId, activity, institutional);
  const date = next.events.find((item) => item.id === eventId)!;
  const generated = generatedActivities(state);
  return {
    date: saved!,
    from: {
      activity: saved!.activity!,
      name: generatedActivity(generated, saved!.activity)?.name,
      issue: linksToReview(state).get(eventId),
    },
    to: { activity: date.activity!, name: generatedActivity(generated, date.activity)!.name },
    issueAfter: linksToReview(next).get(eventId),
  };
}

/**
 * Corrects the linked activity of a saved date (**Corrigir atividade vinculada**): only the link of
 * the whole date changes, never its description, dates, offers or ID. It is the only command that
 * swaps a link; it never removes one. Splitting a date between offers is not supported
 * (`docs/pendencias.md`): the campus adjusts the offers of the date and plans another date.
 */
export function changeActivity<S extends ActivityState>(
  state: S,
  eventId: string,
  activity: ActivityRef | undefined,
  institutional: InstitutionalEventSnapshot[],
): S {
  const corrected = correctedDate(state, eventId, activity);
  return recalculateCalendar(
    { ...state, events: state.events.map((item) => (item.id === eventId ? corrected : item)) },
    institutional,
  );
}

/**
 * Shared checks of the three commands. `previous` is the saved date being edited; without it the
 * date is new. Link rule (`links.ts`): an edit keeps the date's own link, even without a generated
 * activity; interval and association checks apply only when start, end, offers or link change.
 */
function applyDate<S extends ActivityState>(
  state: S,
  event: S['events'][number],
  institutional: InstitutionalEventSnapshot[],
  previous?: CalendarEvent,
): S {
  const editing = previous !== undefined;
  const existing = state.events.find((item) => item.id === event.id);
  const edited = dateEdited(previous, event);
  const activity = generatedActivity(generatedActivities(state), event.activity);
  const kept = linkKept(previous, event);
  // Art. 5º first: a meeting that adds days is refused for that reason, not for its periods.
  if (schoolDayEdited(previous, event)) {
    const issue = schoolDayIssue(state, event) ?? activityExtensionIssue(event);
    if (issue) throw new DomainError(issue);
  }
  validateActivityRecord(state, event, {
    stageInterval: edited && !(kept && !activity),
    keptWithoutActivity: kept && !activity,
  });
  if (!event.name.trim()) throw new DomainError('Informe a descrição.');
  if (!['include', 'exclude', 'note'].includes(event.effect))
    throw new DomainError('Tipo de evento inválido.');
  // Only a date of the campus, without effect on the count, in an allowed category (art. 18).
  validateInternalDate(event);
  const modalities = event.scope.offers;
  if (
    !modalities.length ||
    new Set(modalities).size !== modalities.length ||
    modalities.some((item) => !offerIds(state).includes(item))
  )
    throw new DomainError('Selecione ao menos uma forma de oferta/nível válida para o evento.');
  if (event.activity && !activity && !kept)
    throw new DomainError('Atividade inválida para este calendário.');
  const activityOfferId = activity?.offerId;
  if (edited && activityOfferId && (modalities.length !== 1 || modalities[0] !== activityOfferId))
    throw new DomainError('Selecione somente a oferta da atividade.');
  if (edited && activity && !coversDate(state, activity, event))
    throw new DomainError('A atividade vinculada não abrange as ofertas selecionadas.');
  // A kept link without generated activity has no cycle to check its dates against.
  const cycleIssue = edited && activity ? assessmentCycleIssue(state, event) : undefined;
  if (cycleIssue) throw new DomainError(cycleIssue);
  if (
    event.hours !== undefined &&
    (!Number.isFinite(event.hours) || event.hours <= 0 || event.hours > 8784)
  )
    throw new DomainError('Carga horária inválida.');
  if (
    event.effect === 'include' &&
    datesBetween(event.start, event.end).some((date) =>
      modalities.some(
        (modality) =>
          !periodsForOffer(state, modality).some(
            (period) => period.start <= date && period.end >= date,
          ),
      ),
    )
  )
    throw new DomainError('Inclusões letivas devem estar dentro dos períodos cadastrados.');
  const updated = { ...event, name: event.name.trim() };
  if (!editing && existing) {
    if (equalValues(existing, updated)) return state;
    throw new DomainError(
      'O identificador do evento já existe. Reabra o registro antes de editar.',
    );
  }
  if (
    state.events.some(
      (item) =>
        item.id !== event.id &&
        sameOccurrence(item, updated) &&
        (!editing || !existing || !sameOccurrence(item, existing)),
    )
  )
    throw new DomainError('Este evento já foi incluído com as mesmas datas.');
  let events = editing
    ? state.events.map((item) => (item.id === event.id ? updated : item))
    : [...state.events, updated];
  if (editing && isAssessmentStage(event.activity))
    events = events.map((item) => {
      if (
        !isAssessmentStage(item.activity) ||
        !item.scope.offers.some((modality) => modalities.includes(modality))
      )
        return item;
      const { assessmentAutoStart: _auto, ...rest } = item;
      return rest;
    });
  return recalculateCalendar({ ...state, events }, institutional);
}
