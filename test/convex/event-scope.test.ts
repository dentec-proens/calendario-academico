/**
 * Scope with confirmation through the real mutations (phase 2, step 7; plan, section 5.3). The
 * stored content is a frozen v4 document converted by `convertContentV5`, as the migration will
 * leave it; the catalogue is the frozen one, so the base of the calendar is the fixture's.
 */
async function stored(item: V4Case) {
  const fixture = await createNativeFixture({
    catalogue: { revision: 1, events: offerAdditionCatalogue() },
  });
  const actor = fixture.asClient('campus-a');
  const offers = item.content.state.offers as {
    kind: 'integrado' | 'graduacao';
    organization: 'anual' | 'semestral';
    label?: string;
  }[];
  const created = await actor
    .mutation(api.calendars.createCalendar, {
      body: {
        campusId: fixture.ids.campuses.a,
        year: item.year,
        offers: offers.map(({ kind, organization, label }) => ({
          kind,
          organization,
          ...(label ? { label } : {}),
        })),
      },
    })
    .then(calendarRecordDates);
  const converted = convertContentV5(item.content, {
    year: item.year,
    submissions: item.submissions,
  })!.document as Pick<Doc<'calendarContents'>, 'state' | 'institutionalSnapshot'>;
  const content = await fixture.client.run(async (ctx) => {
    const row = (await ctx.db
      .query('calendarContents')
      .withIndex('by_calendarId', (q) => q.eq('calendarId', created.id))
      .unique())!;
    await ctx.db.patch(row._id, {
      state: converted.state,
      institutionalSnapshot: converted.institutionalSnapshot,
    });
    return (await ctx.db.get(row._id))!;
  });
  const load = () =>
    actor.query(api.calendars.calendar, { id: created.id }).then(calendarRecordDates);
  const record = await load();
  const save = (state: typeof record.state, version = record.version) =>
    actor
      .mutation(api.calendars.saveCalendar, {
        id: record.id,
        body: {
          version,
          catalogueRevision: record.catalogueRevision,
          state: JSON.parse(JSON.stringify(state)) as typeof state,
        },
      })
      .then(calendarSaveDates);
  const storedHash = () =>
    fixture.client.run(async (ctx) => contentHash((await ctx.db.get(content._id))!));
  return { fixture, actor, record, load, save, storedHash, id: created.id };
}

test('adding an offer neither extends nor confirms any scope and keeps the count of the oracle', async () => {
  const { record, load, save } = await stored(offerAdditionCase());
  const originalOffers = record.state.offers.map((offer) => offer.id);
  const state = record.state as unknown as ScopeState;
  expect(countingOf(state, record.institutionalSnapshot, originalOffers)).toEqual(oracleCounting());
  const saved = await save(withNewOffer(state) as unknown as typeof record.state);
  expect(saved.version).toBe(record.version + 1);
  const loaded = await load();
  expect(loaded.state.offers.map((offer) => offer.id)).toEqual([...originalOffers, newOffer.id]);
  for (const event of record.state.events)
    expect(loaded.state.events.find((item) => item.id === event.id)?.scope, event.id).toEqual(
      event.scope,
    );
  expect(
    countingOf(loaded.state as unknown as ScopeState, loaded.institutionalSnapshot, originalOffers),
  ).toEqual(oracleCounting());
});

test('saving a newly converted calendar with vacations and Saturdays, unchanged, writes nothing', async () => {
  const item = offerAdditionCase();
  // Format 4 dates generated by the system had no offers: regenerated vacations discarded them,
  // and Saturdays were created without them. Vacations follow every other date, as saved.
  item.content.state.teacherVacations = {
    firstStart: '2027-01-04',
    firstEnd: '2027-01-18',
    secondStart: '2027-07-12',
    secondEnd: '2027-07-23',
  };
  item.content.state.events.push(
    {
      id: 'saturday-1',
      name: 'Sábado letivo',
      start: '2027-03-06',
      end: '2027-03-06',
      kind: 'include',
      category: 'sabado',
    },
    {
      id: 'teacher-vacation-january',
      name: 'Férias docentes — 15 dias',
      start: '2027-01-04',
      end: '2027-01-18',
      kind: 'exclude',
      category: 'ferias',
    },
    {
      id: 'teacher-vacation-july',
      name: 'Férias docentes — 12 dias',
      start: '2027-07-12',
      end: '2027-07-23',
      kind: 'exclude',
      category: 'ferias',
    },
  );
  const { record, save, load, storedHash } = await stored(item);
  const unconfirmed = { offers: record.state.offers.map((offer) => offer.id), confirmed: false };
  for (const id of ['saturday-1', 'teacher-vacation-january', 'teacher-vacation-july'])
    expect(record.state.events.find((event) => event.id === id)?.scope).toEqual(unconfirmed);
  const hash = await storedHash();
  const saved = await save(record.state);
  expect(saved.unchanged).toBe(true);
  expect(saved.version).toBe(record.version);
  expect(await storedHash()).toBe(hash);
  expect((await load()).state).toEqual(record.state);
});

test('confirming the scope as the only change shows in the comparison with the submission', async () => {
  const { fixture, actor, record, load, save, storedHash, id } = await stored(offerAdditionCase());
  await preserveSubmission(fixture, id as Id<'calendars'>);
  const current = await load();
  const before = await storedHash();
  const note = current.state.events.find((event) => event.id === 'legacy-note')!;
  expect(note.scope.confirmed).toBe(false);
  // Saving the date form unchanged confirms the offers listed in it.
  const confirmed = eventFromValues(eventValues(note), { id: note.id, base: note });
  expect(confirmed).toEqual({ ...note, scope: { ...note.scope, confirmed: true } });
  const saved = await save(
    {
      ...current.state,
      events: current.state.events.map((event) => (event.id === note.id ? confirmed : event)),
    },
    current.version,
  );
  expect(saved.unchanged).toBeFalsy();
  expect(saved.version).toBe(current.version + 1);
  expect(await storedHash()).not.toBe(before);
  const { page } = await actor.query(api.calendars.calendarSubmissions, {
    id: record.id,
    paginationOpts: { numItems: 10, cursor: null },
  });
  const copy = submissionDates(
    await actor.query(api.calendars.submissionContent, {
      id: record.id,
      submissionId: page[0].id as Id<'calendarSubmissions'>,
    }),
  );
  const after = await load();
  const side = (value: {
    state: unknown;
    institutionalSnapshot: unknown;
    documentSnapshot: unknown;
    catalogueRevision: number;
  }) => value as unknown as DiffSide;
  const diff = compareContents(side(copy), side(after));
  expect(diff.events).toEqual([
    {
      kind: 'changed',
      id: 'legacy-note',
      name: note.name,
      fields: [
        { field: 'scope.confirmed', label: 'Abrangência confirmada', before: false, after: true },
      ],
    },
  ]);
  expect(diff.campusChanges).toBe(1);
});
