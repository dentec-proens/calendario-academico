/**
 * Generates the static Open Sans faces the printed calendar uses (assets/printing/fonts).
 *
 * Chromium's PDF engine writes a variable font as Type 3 glyphs, and PDF readers such as Preview
 * then refuse to select or copy that text. A static instance of the same font is written as
 * TrueType, so the PDF keeps its text. Each face pins the variable font's weight and width axes at
 * a value calendar.css uses; the outlines and metrics are the same, so the pages do not reflow.
 *
 * Needs `uvx` (uv) to run fontTools: `pnpm exec tsx scripts/build-print-fonts.ts`.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const source = dirname(
  createRequire(import.meta.url).resolve('@fontsource-variable/open-sans/package.json'),
);
const output = join(import.meta.dirname, '..', 'assets', 'printing', 'fonts');

// The ranges are fontsource's, so each file only downloads when the page uses its characters.
const subsets = {
  latin:
    'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
  'latin-ext':
    'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
};
// Weights and widths calendar.css asks for: body, the 650 labels, bold, and the narrower events,
// plus upright 500 latin for school-day numbers in the month grid and key.
const specs = [
  ...(['latin', 'latin-ext'] as const).flatMap((subset) =>
    (['normal', 'italic'] as const).flatMap((style) =>
      [400, 650, 700].flatMap((weight) =>
        [100, 87.5].map((width) => ({ subset, style, weight, width })),
      ),
    ),
  ),
  { subset: 'latin' as const, style: 'normal' as const, weight: 500, width: 100 },
];

rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
const faces: string[] = [];
for (const { subset, style, weight, width } of specs) {
  const range = subsets[subset];
  const file = `open-sans-${subset}-${weight}-${String(width).replace('.', '_')}-${style}.woff2`;
  execFileSync(
    'uvx',
    [
      '--from',
      'fonttools==4.60.1',
      '--with',
      'brotli==1.1.0',
      'fonttools',
      'varLib.instancer',
      join(source, 'files', `open-sans-${subset}-wdth-${style}.woff2`),
      `wght=${weight}`,
      `wdth=${width}`,
      '--quiet',
      '-o',
      join(output, file),
    ],
    { stdio: 'inherit' },
  );
  faces.push(`@font-face {
  font-family: 'Open Sans Print';
  font-style: ${style};
  font-weight: ${weight};
  font-stretch: ${width}%;
  font-display: swap;
  src: url(./${file}) format('woff2');
  unicode-range: ${range};
}`);
}
writeFileSync(
  join(output, 'open-sans.css'),
  `/* Generated by scripts/build-print-fonts.ts: static faces, so the PDF keeps selectable text. */\n${faces.join('\n')}\n`,
);
